export function photoById(id: PhotoId) {
  const photo = PHOTOS.find((p) => p.id === id);
  if (!photo) throw new Error(`Foto mancante: ${id}`);
  return photo;
}

export function assetById(id: string) {
  return ASSETS.find((a) => a.id === id);
}

export function zoneById(id: string) {
  return ZONES.find((z) => z.id === id);
}

export function assetsInPhoto(id: PhotoId) {
  return ASSETS.filter((a) => a.appearsIn.includes(id));
}

export const HARDWARE_ASSETS = ASSETS.filter((a) => a.needsHardwareModel);
export const DESK_ASSETS = ASSETS.filter((a) => a.collection === "desk");
export const ROOM_ASSETS = ASSETS.filter((a) => a.collection === "room");
